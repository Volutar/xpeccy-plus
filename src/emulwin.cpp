// what happens to the window happens to the frame
bool MainWin::eventFilter(QObject* obj, QEvent* ev) {
	if (obj == frame) {
		switch (ev->type()) {
			case QEvent::Move:
				// where the window goes back to: fullscreen moves it too
				if (!conf.vid.fullScreen && !frame->isFullScreen()) {
					conf.xpos = frame->pos().x();
					conf.ypos = frame->pos().y();
				}
				emit s_keywin_snap();
				break;
			case QEvent::Close:
				closeEvent(static_cast<QCloseEvent*>(ev));	// accepts or ignores it
				return true;
			default:
				break;
		}
	}
	// the status bar's tape and drives: a click opens their window, the right button their menu
	int drv = -1;
	for (int i = 0; i < 4; i++)
		if (obj == sbDiskBox[i]) drv = i;
	if ((obj == sbTapeBox) || (drv >= 0)) {
		if ((ev->type() == QEvent::MouseButtonPress) && (static_cast<QMouseEvent*>(ev)->button() == Qt::LeftButton)) {
			if (drv < 0) {
				emit s_tape_show();
			} else {
				diskWin->showWindow();
			}
			return true;
		}
		if (ev->type() == QEvent::ContextMenu) {
			QPoint pos = static_cast<QContextMenuEvent*>(ev)->globalPos();
			if (drv < 0) {
				tapeMenu(pos);
			} else {
				fillDrivesMenu();
				if (flpMenu[drv]) flpMenu[drv]->exec(pos);
			}
			setFocus();
			return true;
		}
	}
	return QObject::eventFilter(obj, ev);
}

