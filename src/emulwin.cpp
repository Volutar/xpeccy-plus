// what happens to the window happens to the frame
bool MainWin::eventFilter(QObject* obj, QEvent* ev) {
	if (obj == frame) {
		switch (ev->type()) {
			case QEvent::Show:
				if (QWindow* win = frame->windowHandle()) {
					connect(win, &QWindow::screenChanged, this, &MainWin::updateScreen, Qt::UniqueConnection);
					updateScreen(win->screen());
				}
				break;
			case QEvent::Move:
				// where the window goes back to: fullscreen moves it too
				if (!conf.vid.fullScreen && !frame->isFullScreen()) {
					conf.xpos = frame->pos().x();
					conf.ypos = frame->pos().y();
				}
				emit s_keywin_snap();
				break;
			case QEvent::Resize:
				// a new zoom or border: the frame takes its size after updateWindow()
				// has asked for it, so a docked keyboard is told again from here
				emit s_keywin_snap();
				break;
			case QEvent::Close:
				closeEvent(static_cast<QCloseEvent*>(ev));	// accepts or ignores it
				return true;
			default:
				break;
		}
	}
	// the status bar's machine name: either button opens the Machine menu, the left one
	// over the name as a menu from a bar at the bottom, the right one at the pointer
	if (obj == sbMachine) {
		QPoint pos;
		if ((ev->type() == QEvent::MouseButtonPress) && (static_cast<QMouseEvent*>(ev)->button() == Qt::LeftButton)) {
			pos = sbMachine->mapToGlobal(QPoint(0, 0)) - QPoint(0, profileMenu->sizeHint().height());
		} else if (ev->type() == QEvent::ContextMenu) {
			pos = static_cast<QContextMenuEvent*>(ev)->globalPos();
		} else {
			return QObject::eventFilter(obj, ev);
		}
		profileMenu->exec(pos);
		setFocus();
		return true;
	}
	// the divMMC's light: either button, its cards. The status bar changes what is
	// in the machine, not what the machine is, so the board's switch is not here.
	if (obj == sbCardBox) {
		bool left = (ev->type() == QEvent::MouseButtonPress) && (static_cast<QMouseEvent*>(ev)->button() == Qt::LeftButton);
		if (!left && (ev->type() != QEvent::ContextMenu))
			return QObject::eventFilter(obj, ev);
		QMenu menu(this);
		addDivCards(&menu);
		// the left button's over the light, as from a bar at the bottom; the right one at the pointer
		QPoint pos = left ? sbCardBox->mapToGlobal(QPoint(0, 0)) - QPoint(0, menu.sizeHint().height())
			: static_cast<QContextMenuEvent*>(ev)->globalPos();
		menu.exec(pos);
		setFocus();
		return true;
	}
	// the status bar's tape and drives: a click opens their window, the right button their menu
	int drv = -1;
	for (int i = 0; i < 4; i++)
		if (obj == sbDiskBox[i]) drv = i;
	if ((obj == sbTapeBox) || (drv >= 0)) {
		if ((ev->type() == QEvent::MouseButtonPress) && (static_cast<QMouseEvent*>(ev)->button() == Qt::LeftButton)) {
			if (drv < 0) {
				emit s_tape_show();
			} else {
				diskWin->showWindow();
			}
			return true;
		}
		if (ev->type() == QEvent::ContextMenu) {
			QPoint pos = static_cast<QContextMenuEvent*>(ev)->globalPos();
			if (drv < 0) {
				tapeMenu(pos);
			} else {
				fillDrivesMenu();
				if (flpMenu[drv]) {
					flpMenu[drv]->exec(pos);
				} else if (conf.zx->dif->out) {
					dskMenu->exec(pos);		// why it is off, and the way back
				}
			}
			setFocus();
			return true;
		}
	}
	return QObject::eventFilter(obj, ev);
}

