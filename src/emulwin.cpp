	vid_upd_scale();
	updateWindow();
	// hasPicture: at start-up there is nothing in the buffer to clean up after,
	// and the machine must not be stepped before the event loop is up
	if (hasPicture) {
		renderFrame();
		presentFrame();
	}
//	saveConfig();
