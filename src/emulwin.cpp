// A hotkey as a menu item. The key goes in the text and not in setShortcut:
// a shortcut would take the key before the machine sees it, grabbed or not.
// One action per hotkey, whatever shows it - a menu, the toolbar or both.
QAction* MainWin::cutAct(const QString& name, int id, const QString& icon) {
	QAction* act = cutById.value(id);
	if (act) return act;
	act = new QAction(name, this);
	if (!icon.isEmpty()) act->setIcon(QIcon(":/images/" + icon + ".png"));
	connect(act, &QAction::triggered, this, [this, id]() {
		xkey_press(id, true);
		xcut_release(id);
	});
	cutActs.append({act, name, id});
	cutById[id] = act;
	return act;
}

QAction* MainWin::cutAction(QMenu* menu, const QString& name, int id, const QString& icon) {
	QAction* act = cutAct(name, id, icon);
	menu->addAction(act);
	return act;
}

