#if defined(USEOPENGL) && !BLOCKGL
// The GL view's paint: the frame through the shader, then the indicators.
void MainWin::paintGLView() {
	// Qt paints the window on its own too - an expose, a menu closing. The
	// framebuffer keeps the last frame for that, and the frame is drawn only
	// when presentFrame() asks. Updates are not switched off instead: Qt then
	// skips this widget when it paints the window, and the window's background
	// stays over the picture.
	// A new framebuffer is the one exception: a size change leaves it empty, and
	// it would show black until the next frame comes.
	if (!paintOwed) return;
	paintOwed = 0;
	QPainter pnt(glw);
	pnt.beginNativePainting();
	glClearColor(0, 0, 0, 1);
	glClear(GL_COLOR_BUFFER_BIT);

	// Low latency: take the newest frame and drop the rest for the lowest
	// lag. Buffered: take the oldest (FIFO) so the small buffer smooths jitter.
	if (!queue.isEmpty()) {
		if (conf.vid.lowLatency) {
			curtxid = queue.takeLast();
			queue.clear();
		} else {
			curtxid = queue.takeFirst();
		}
		dsync_frame_drawn();
	}

	// The window (or the border) has just changed. Read the frame out of the
	// buffer again with the new bounds instead of stretching the old texture
	// over the new window - and while the machine is paused, no new frame is
	// coming to do it later.
	if (refit && prg.isLinked()) {		// isLinked: initializeGL has run, texids are real
		refit = 0;
		glBindTexture(GL_TEXTURE_2D, texids[curtex]);
		uploadFrame();
		curtxid = texids[curtex];
		queue.clear();
	}

	// curtxid stays 0 until the emulation thread hands over its first frame,
	// and the window is painted before that happens. Binding a texture name
	// that was never generated is undefined - macOS says so out loud, other
	// drivers quietly sample black.
	drawPicture();
	glFlush();
	pnt.endNativePainting();
	drawInputOsd(pnt);
	drawIcons(pnt);
	pnt.end();
#if !ISLEGACYGL
	if (vrec_wants_screen()) {
		grabScreen();
		// the sign is the user's alone: the picture under it is drawn again
		int rec = recOsd();
		if (rec != osd_none) {
			const qreal r = widgetDpr(this);
			QRect slot = modeSlot();
			QPainter top(glw);
			top.beginNativePainting();
			glEnable(GL_SCISSOR_TEST);
			glScissor(int(slot.x() * r), int((height() - slot.bottom() - 1) * r),
				int(slot.width() * r + 1), int(slot.height() * r + 1));
			glClearColor(0, 0, 0, 1);
			glClear(GL_COLOR_BUFFER_BIT);
			drawPicture();
			glDisable(GL_SCISSOR_TEST);
			glFlush();
			top.endNativePainting();
			top.drawImage(slot.topLeft(), osdImg[rec]);
			top.end();
		}
	}
#endif
}
#endif

// the frame, through the shader, where drawX/Y/W/H say
void MainWin::drawPicture() {
#if defined(USEOPENGL) && !BLOCKGL
	if (prg.isLinked() && curtxid) {
		const qreal r = widgetDpr(this);
		Computer* comp = conf.zx;
		const GLfloat tex_w = GLfloat(comp->vid->vsze.x * 2);
		const GLfloat tex_h = GLfloat(comp->vid->vsze.y);
		// the quad covers the viewport, and the viewport is the picture: in
		// fullscreen it is a whole-zoom rectangle in the middle of the screen,
		// with the cleared black around it
		glViewport(int(drawX * r + 0.5), int(drawY * r + 0.5),
			int(drawW * r + 0.5), int(drawH * r + 0.5));
		static const QMatrix4x4 legacyMvp = []{
			QMatrix4x4 m;
			m.ortho(0.0f, 1.0f, 1.0f, 0.0f, -1.0f, 1.0f);
			return m;
		}();
		prg.bind();
		prg.setUniformValue("u_tex", 0);
		prg.setUniformValue("rubyTexture", 0);
		prg.setUniformValue("u_mvp_", legacyMvp);
		prg.setUniformValue("rubyInputSize",   tex_w, tex_h);
		prg.setUniformValue("rubyTextureSize", tex_w, tex_h);
		prg.setUniformValue("rubyOutputSize",  GLfloat(drawW * r), GLfloat(drawH * r));

		glActiveTexture(GL_TEXTURE0);
		glBindTexture(GL_TEXTURE_2D, curtxid);

		vao.bind();
		glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);
		vao.release();

		prg.release();
	}
#endif
}

// The window as it was just painted, shader and indicators and all. Read
// straight after the paint, while the context is current and the widget's
// framebuffer holds it.
void MainWin::grabScreen() {
#if defined(USEOPENGL) && !BLOCKGL && !ISLEGACYGL
	const qreal r = widgetDpr(this);
	int fw = int(width() * r + 0.5);
	int fh = int(height() * r + 0.5);
	QImage img(fw & ~1, fh & ~1, QImage::Format_RGBA8888);
	glBindFramebuffer(GL_FRAMEBUFFER, glw->defaultFramebufferObject());
	glPixelStorei(GL_PACK_ALIGNMENT, 4);
	glReadPixels(0, fh - img.height(), img.width(), img.height(), GL_RGBA, GL_UNSIGNED_BYTE, img.bits());
	vrec_screen(img);
#endif
}

// An RZX recording of the machine from here on, or of the one being played
// from the frame it has got to, into a file asked for first.
void MainWin::rzxRec(bool finalize) {
	Computer* comp = conf.zx;
	QString path;
	if (!rzxr_on()) {
		pause(true, PR_FILE);
		// over a recording being played, the recording goes on in its own file
		QString own = comp->rzx.play ? rzx_current() : QString();
		path = file_ask_save("Record RZX", "RZX recording (*.rzx)", ".rzx", own.isEmpty() ? rzxr_suggest() : own, own);
		pause(false, PR_FILE);
		if (path.isEmpty()) {
			emit s_rzx_rec(false);
			return;
		}
	}
	emu_lock();
	int err = ERR_OK;
	if (rzxr_on()) {
		rzxr_stop(comp, finalize);
	} else {
		err = rzxr_start(comp, path);
	}
	emu_unlock();
	if (err != ERR_OK) {
		setMessage(" this machine cannot be recorded ");
	} else if (rzxr_on()) {
		setMessage(" RZX recording ");
	}
	rzxWatch();
	emit s_rzx_rec(rzxr_on());
}

// A recording on disk goes on: it is opened, run to its end flat out, and taken
// over there - rzxContStep() follows it to that point.
void MainWin::rzxContinue() {
	if (rzxr_on()) return;
	unsigned was = rzx_playing;
	openMedia(QString(), FG_RZX, -1, 0, false);
	rzxContStage = (rzx_playing && (rzx_playing != was)) ? 1 : 0;
}

void MainWin::rzxContStep() {
	Computer* comp = conf.zx;
	if (!rzxContStage) return;
	if (!rzx_playing) {				// stopped or closed meanwhile
		rzxContStage = 0;
		return;
	}
	if (!comp->rzx.play) return;			// not started yet
	if (rzxContStage == 1) {
		rzxContStage = 2;
		rzxSeek(std::max(comp->rzx.fTotal - 1, 0));
	} else if (!rzx_seeking()) {
		rzxContStage = 0;
		rzxRec();
	}
}

// A file on disk loses its bookmarks, the snapshots kept to roll back to.
void MainWin::rzxFinalizeFile() {
	pause(true, PR_FILE);
	QString path = file_ask_load("Finalize RZX", "RZX recording (*.rzx)");
	if (!path.isEmpty()) {
		int err = rzxr_finalize_file(path);
		if (err == ERR_OK) {
			setMessage(" RZX finalized ");
		} else {
			file_errors(err);
		}
	}
	pause(false, PR_FILE);
}

// A name that says what was on the machine: the image in use, else the machine.
void MainWin::videoRec() {
	vrec_manual();		// the hotkey has the last word over auto recording
	if (vrec_state() == VREC_RUN) {
		vrec_stop();
		setMessage(" video: finishing ");
		return;
	}
	// none yet: offer one, and the next press records
	if (vrec_ffmpeg().isEmpty()) {
		ffmpeg_get(this);
		return;
	}
	recStart();
}

// file: the one the command line names, else the settings' folder and template
bool MainWin::recStart(const QString& file) {
	Computer* comp = conf.zx;
	int sw = 0;
	int sh = 0;
#if defined(USEOPENGL) && !BLOCKGL && !ISLEGACYGL
	if (glw && (conf.rec.source == VREC_SRC_SCREEN)) {
		const qreal r = widgetDpr(this);
		sw = int(width() * r + 0.5);
		sh = int(height() * r + 0.5);
	}
#endif
	QString err;
	// started, the blinking sign says so: a message would be in the video
	if (vrec_start(comp, media_image_name(), sw, sh, &err, file)) return true;
	setMessage(QString(" video: %0 ").arg(err), 4.0);
	xlog(XLG_VIDEO, XLL_WARN, "recording not started: %s", err.toLocal8Bit().data());
	return false;
}

#define MODE_ICON_W	60	// the pictures are twice this
#define MODE_ICON_TOP	22	// below the fps readout
#define MODE_ICON_TOP_NOFPS	5	// with no fps readout to clear
#define MODE_ICON_RIGHT	5
#define RW_SECS_LINGER	1500	// ms the rewind's seconds stay up after it
#define SIGN_FADE_MS	500	// and any other sign
#define SIGN_FADE_FROM	0.6	// how pale a sign turns as soon as it is over
#define MSG_FADE_FRAMES	25	// the last frames of a message, fading
#define REC_BLINK_MS	500

// where the speed mode and the recording sign go
// the status bar has the rate, when it is there
bool MainWin::fpsOsd() {
	return conf.led.fps && !statusBar->isVisible();
}

QRect MainWin::modeSlot() {
	return QRect(width() - MODE_ICON_W - MODE_ICON_RIGHT, fpsOsd() ? MODE_ICON_TOP : MODE_ICON_TOP_NOFPS,
		MODE_ICON_W, MODE_ICON_W * 3 / 5);
}

// the speed mode, VCR style
int MainWin::speedOsd() {
	if (conf.emu.pause)		// the one place a pause shows
		return osd_pause;
	if (rewind_active())
		return osd_rewind;
	if (conf.emu.fast)
		return osd_fast;
	if (conf.emu.speed != 1.0) {
		int e = ilogb(conf.emu.speed);		// x2 x4 x8 are 1..3, 1/2 1/4 1/8 are -1..-3
		return (e > 0) ? osd_ffwd2 + e - 1 : osd_slow2 - e - 1;
	}
	return osd_none;
}

// the recording sign now: it blinks, and its dark phase gives way to a speed mode
// A video says REC, an RZX recording RZX; both at once take turns.
int MainWin::recOsd() {
	bool vid = (vrec_state() == VREC_RUN);
	bool rzx = rzxr_on();
	if (!vid && !rzx) return osd_none;
	long long phase = QDateTime::currentMSecsSinceEpoch() / REC_BLINK_MS;
	bool showRzx = rzx && (!vid || (phase & 2));
	if (!(phase & 1)) return showRzx ? osd_rzx : osd_rec;
	return (speedOsd() == osd_none) ? (showRzx ? osd_rzx_off : osd_rec_off) : osd_none;
}

void MainWin::drawIcons(QPainter& pnt) {
	Computer* comp = conf.zx;
// screenshot
	if (scrCounter > 0) {
		if (scrInterval > 0) {
			scrInterval--;
		} else {
			scrInterval = conf.scrShot.interval;
			scrCounter--;
			screenShot();
		}
	}
// put leds
// keyboard
	// ALF is a ZX with no keyboard at all, so the test is keyp
	if (conf.led.keys && comp->hw->keyp) {
		pnt.drawImage(3, 10, leds[led_kbd]);
		if (~comp->keyb->port & 0x01) pnt.fillRect(3 + 3, 10 + 17, 8, 2, Qt::gray);
		if (~comp->keyb->port & 0x02) pnt.fillRect(3 + 3, 10 + 14, 8, 2, Qt::gray);
		if (~comp->keyb->port & 0x04) pnt.fillRect(3 + 3, 10 + 11, 8, 2, Qt::gray);
		if (~comp->keyb->port & 0x08) pnt.fillRect(3 + 3, 10 + 8, 8, 2, Qt::gray);
		if (~comp->keyb->port & 0x80) pnt.fillRect(3 + 12, 10 + 17, 8, 2, Qt::gray);
		if (~comp->keyb->port & 0x40) pnt.fillRect(3 + 12, 10 + 14, 8, 2, Qt::gray);
		if (~comp->keyb->port & 0x20) pnt.fillRect(3 + 12, 10 + 11, 8, 2, Qt::gray);
		if (~comp->keyb->port & 0x10) pnt.fillRect(3 + 12, 10 + 8, 8, 2, Qt::gray);
	}
	comp->keyb->port = 0xff;
	// the status bar has these, when it is there
	bool osd = !statusBar->isVisible();
// joystick
	if (comp->joy->used) {
		joySeen = true;
		if (conf.led.joy && osd) pnt.drawImage(3, 30, leds[led_joy]);
		comp->joy->used = 0;
	}
// mouse
	if (comp->mouse->used) {
		mouseReadAt = paceClockNs();
		mouseSeen = true;
		if (conf.led.mouse && osd) pnt.drawImage(3, 50, leds[led_mouse]);
		comp->mouse->used = 0;
	}
// tape and disc: as the last look at the lights found them (lightLook), blinking the same way
	if (conf.led.tape && osd) {
		if ((tapeLight >= SB_TAPE_RD) && (tapeLight <= SB_TAPE_WR_HI))
			pnt.drawPixmap(3, 70, sbPix[tapeLight]);
	}
	if (conf.led.disk && osd) {
		for (int i = 0; i < 4; i++) {
			if (comp->dif->flp[i] != comp->dif->fdc->flp) continue;		// the drive the controller has
			if (diskLight[i] == SB_DISK_RD) pnt.drawImage(3, 90, leds[led_disk_green]);
			if (diskLight[i] == SB_DISK_WR) pnt.drawImage(3, 90, leds[led_disk_red]);
		}
	}
	// kept for the next look at the lights
	for (int i = 0; i < 4; i++) {
		Floppy* flp = comp->dif->flp[i];
		flpSeen[i] |= (flp->rd ? 1 : 0) | (flp->wr ? 2 : 0) | ((flp->trk != flpTrk[i]) ? 4 : 0);
		flpTrk[i] = flp->trk;
		flp->rd = 0;
		flp->wr = 0;
	}
// waveout
	if (conf.snd.wavout) {
		pnt.drawImage(3, 110, leds[led_wav]);
	}
// put the speed mode, VCR style, clear of the fps readout
	int mode = speedOsd();
	// A sign whose state is over fades away rather than blinking out - pale at
	// once, so it does not read as still on. The rewind's stays longer: its
	// seconds under it are there to be read.
	static int signOn = osd_none;
	static int signGone = osd_none;
	static qint64 signGoneAt = 0;
	qint64 now = QDateTime::currentMSecsSinceEpoch();
	if (mode != osd_none) {
		signOn = mode;
		signGone = osd_none;
	} else if (signOn != osd_none) {
		signGone = conf.led.fade ? signOn : osd_none;
		signGoneAt = now;
		signOn = osd_none;
	}
	double fade = 1.0;
	if ((mode == osd_none) && (signGone != osd_none)) {
		int len = (signGone == osd_rewind) ? RW_SECS_LINGER : SIGN_FADE_MS;
		if (now - signGoneAt < len) {
			mode = signGone;
			fade = SIGN_FADE_FROM * (1.0 - double(now - signGoneAt) / len);
		} else {
			signGone = osd_none;
		}
	}
	// recording blinks, taking turns with the speed mode. Recording the window,
	// it is put on after the picture has been read (see paintEvent)
	int rec = recOsd();
	if ((rec != osd_none) && !vrec_wants_screen()) {
		mode = rec;
		fade = 1.0;
	}
	pnt.setOpacity(fade);
	if (mode != osd_none)
		pnt.drawImage(modeSlot().topLeft(), osdImg[mode]);
	// how far back a rewind has gone, under its sign, to the right like it and the
	// same gap below it as to the edge
	if (mode == osd_rewind) {
		int t = rewind_back_tenths();
		snprintf(numbuf, sizeof(numbuf), " -%d.%ds ", t / 10, t % 10);
		QRect slot = modeSlot();
		drawText(&pnt, width() - strlen(numbuf) * 12 - MODE_ICON_RIGHT, slot.bottom() + 1 + MODE_ICON_RIGHT, numbuf);
	}
	pnt.setOpacity(1.0);
// put fps
	if (fpsOsd()) {
		snprintf(numbuf, sizeof(numbuf), " %.1f ", conf.vid.curfps);
		drawText(&pnt, width() - (strlen(numbuf) * 12) - 5, 5, numbuf);
	}
// put halt counter
	if (conf.led.halt) {
		snprintf(numbuf, sizeof(numbuf), " %d : %d ",comp->hCount, comp->fCount);
		drawText(&pnt, width() - strlen(numbuf) * 12 - 8, height() - 20, numbuf);
	}
// put cpu clock, but only when it is not the one the machine ships with: it is
// there to say a run was not on stock timings, and drops to the tick counter's
// line when that is switched off. The status bar has it, when it is there
	double clk = xspeed_clock();
	if (conf.led.clock && osd && (fabs(clk - comp->cpuFrq) > 1e-6)) {
		snprintf(numbuf, sizeof(numbuf), " %.6g MHz ", clk);
		drawText(&pnt, width() - strlen(numbuf) * 12 - 8, height() - (conf.led.halt ? 40 : 20), numbuf);
	}
// put messages
	if (msgTimer > 0) {
		if (conf.led.message) {
			if (conf.led.fade && (msgTimer < MSG_FADE_FRAMES))	// its last moments, fading
				pnt.setOpacity(double(msgTimer) / MSG_FADE_FRAMES);
			drawText(&pnt, 5, height() - 20, msg.toLocal8Bit().data());
			pnt.setOpacity(1.0);
		}
		msgTimer--;
		if (msgTimer == 0) {
			msgHeld = false;
			msg = msgNext;
			msgTimer = msgNextTimer;
			msgNextTimer = 0;
		}
	}
// end
}

