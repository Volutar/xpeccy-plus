void MainWin::updateHead() {
	QStringList parts;
	QString media = media_current();
	if (!media.isEmpty())
		parts << QFileInfo(media).fileName();
	parts << XPTITLE;
#ifdef ISDEBUG
	parts << "debug";
#endif
	const xMachine* mac = xm_find(conf.macId);
	if (conf.zx && mac)
		parts << QString::fromLocal8Bit(mac->name.c_str());
	if (conf.emu.fast && !autostart_busy() && !fastload_busy())	// neither fast mode is the user's
		parts << "fast";
	frame->setWindowTitle(parts.join(" - "));
}

void MainWin::updateWindow() {
	block = 1;
	// the texture still holds the frame cut to the old bounds, and painting it
	// into the resized window would stretch it until the next frame arrives
	refit = 1;
	QSize wsz;
	Computer* comp = conf.zx;
	vid_set_zoom(conf.vid.scale);		// where the picture goes, and how big
	// a size change can switch the shader off or bring it back (wantedShader)
	if (conf.vid.shd_support && (wantedShader() != shdLoaded))
		loadShader();
	blockSignals(true);
	showBars();
	if (conf.vid.fullScreen) {
#if defined(__WIN32)
		fsTall = fsWantTall(fsHeld());
#endif
		wsz = SCREENSIZE + QSize(0, fsTall ? 1 : 0);
		frame->setWindowState(frame->windowState() | Qt::WindowFullScreen);
	} else {
		// the picture: a whole number of pixels per dot, or it would be
		// resampled and some columns come out a pixel wider than others
		wsz = QSize(drawW, drawH);
		// Qt 5 forgets a widget is fullscreen once it has been resized - the layout
		// does that - while its window stays so, and leaving would then do nothing,
		// title bar never coming back: the widget is told fullscreen again first.
		QWindow* win = frame->windowHandle();
		if (win && (win->windowStates() & Qt::WindowFullScreen))
			frame->setWindowState(frame->windowState() | Qt::WindowFullScreen);
		frame->setWindowState(frame->windowState() & ~Qt::WindowFullScreen);
	}
	setFixedSize(wsz);
	blockSignals(false);
	// the buffer holds the whole raster, whatever part of it is shown
	bytesPerLine = comp->vid->full.x * 8;
	bufSize = bytesPerLine * comp->vid->full.y * (comp->vid->linedbl ? 2 : 1);
	updateHead();
	block = 0;
	emit s_keywin_snap();		// a docked keyboard follows the new size
}

bool MainWin::saveChanged() {
	bool yep = true;
	QString str;
	Floppy* flp;
	for (int i = 0; (i < 4) && yep; i++) {
		flp = conf.zx->dif->flp[i];
		if (!flp->changed) continue;
		str = QString("Disk %0 was changed<br>Save it?").arg(QChar('A' + i));
		switch (askYNC(str.toLocal8Bit().data())) {
			case QMessageBox::Yes:
				yep &= save_file(conf.zx, flp->path, FG_DISK, i);
				break;
			case QMessageBox::Cancel:
				yep = false;
				break;
		}
	}
	return yep;
}

void MainWin::pause(bool p, int msk) {
	conf.emu.fast = 0;
	if (p) {
		conf.emu.pause |= msk;
	} else {
		conf.emu.pause &= ~msk;
	}
	if (!grabMice || (conf.emu.pause && grabMice)) {
		releaseMouse();
	}
	if (!conf.emu.pause) {
		if (grabMice) {
			grabMouse(QCursor(Qt::BlankCursor));
			mouseRecenter();	// the pointer went its own way while paused
		}
		mapReplayHeld(conf.gpctrl->gpada);
		mapReplayHeld(conf.gpctrl->gpadb);
	}
}

