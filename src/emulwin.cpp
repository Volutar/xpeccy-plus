// Hand the shown part of the raster to the texture. The rest of the buffer is
// skipped by the unpack settings, so the frame stays whole in memory and can be
// read out again with new bounds - that is what makes a border change take
// effect at once, even while the machine is paused.
void MainWin::uploadFrame() {
#if defined(USEOPENGL) && !BLOCKGL
	Computer* comp = conf.zx;
	Video* vid = comp->vid;
	// GL_UNPACK_ROW_LENGTH and friends are core in GL 3.3 and GLES 3.0, which
	// is what the shaders here ask for anyway ("#version 330" / "300 es"), so
	// a context that has no unpack settings could not draw the picture either
	glPixelStorei(GL_UNPACK_ROW_LENGTH, vid->full.x * 2);
	glPixelStorei(GL_UNPACK_SKIP_PIXELS, vid->lcut.x * 2);
	glPixelStorei(GL_UNPACK_SKIP_ROWS, vid->lcut.y);
	const unsigned char* img = frame_shown_lock();
	glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, vid->vsze.x * 2, vid->vsze.y, 0,
		GL_RGBA, GL_UNSIGNED_BYTE, comp->flgDBG ? scrimg : img);
	frame_shown_unlock();
	glPixelStorei(GL_UNPACK_ROW_LENGTH, 0);
	glPixelStorei(GL_UNPACK_SKIP_PIXELS, 0);
	glPixelStorei(GL_UNPACK_SKIP_ROWS, 0);
#endif
}

// Same upload, but from a timer or the emulation thread's frame signal rather
// than from paintEvent, so the context has to be taken first - calling GL
// without it is undefined and crashes some drivers.
void MainWin::uploadOffPaint() {
#if defined(USEOPENGL) && !BLOCKGL
	makeCurrent();
	glBindTexture(GL_TEXTURE_2D, texids[curtex]);
	uploadFrame();
	doneCurrent();
#endif
}

// Redraw now: the one place the picture is drawn (see paintEvent).
void MainWin::presentFrame() {
	blockSignals(true);
	paintOwed = 1;
	repaint();
	blockSignals(false);
}

void MainWin::frame_timer() {
	// No frame yet, so there is nothing in the window - and a window that is
	// never painted is not put on screen at all on macOS. Paint it anyway; no
	// frame is coming meanwhile, so the picture holds still. Autostart is the
	// long case: it runs the machine at full speed and draws no pixels.
	if (!hasPicture) {
		presentFrame();
		return;
	}
	// autostart draws nothing, and what bufimg still holds is the machine from
	// before its reset: the window keeps the picture it had
	if (autostart_busy()) return;
	Computer* comp = conf.zx;
	if (comp) {
		frm_ns += comp->vid->nsPerFrame;
		frm_tmr.setInterval(frm_ns / 1000000);		// 1e6 ns = 1 ms. next frame shot
		frm_ns = frm_ns % 1000000;			// remains
	}
	// In low latency mode d_frame() shows each frame as soon as it is made,
	// so this timer does not paint in normal play (a second timer would beat
	// with frame making and cause a slow frame slip). The timer paints for
	// fast-forward and pause (no frames at 50Hz), and in buffered mode, where
	// a steady timer rate looks smoother.
	if (conf.vid.lowLatency && !conf.emu.fast && !conf.emu.pause) return;
#if defined(USEOPENGL) && !BLOCKGL
	if (conf.emu.fast || conf.emu.pause) {
		// fast loading finishes a picture 30 times a second at most, and one
		// upload of it is enough however often the window is painted
		if (conf.emu.pause || (upSwaps != bufSwaps)) {
			upSwaps = bufSwaps;
			uploadOffPaint();
		}
		queue.clear();
		queue.append(texids[curtex]);
	}
#endif
	presentFrame();
}

void MainWin::d_frame() {
	// before the fast check: a fast load started from the command line makes
	// no frame at normal speed until it is over, and frame_timer() shows
	// nothing without this
	hasPicture = 1;
	if (conf.emu.fast) return;
	upSwaps = -1;		// the texture the timer shows next is not this one
#if defined(USEOPENGL) && !BLOCKGL
	queue.append(texids[curtex]);
	// Low latency keeps only the newest frame; buffered keeps a couple to
	// smooth jitter (see paintEvent).
	if (queue.size() > (conf.vid.lowLatency ? 1 : 2))
		queue.takeFirst();
	uploadOffPaint();
	curtex++;
#endif
	// Low latency: show the frame now. Buffered: let the timer show it.
	if (conf.vid.lowLatency)
		presentFrame();
}

