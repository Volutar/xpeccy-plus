void MainWin::updateHead() {
	QStringList parts;
	QString media = media_current();
	if (!media.isEmpty())
		parts << QFileInfo(media).fileName();
	parts << XPTITLE;
#ifdef ISDEBUG
	parts << "debug";
#endif
	const xMachine* mac = xm_find(conf.macId);
	if (conf.zx && mac)
		parts << QString::fromLocal8Bit(mac->name.c_str());
	if (conf.emu.fast && !autostart_busy() && !fastload_busy() && !rzx_seeking())	// none of them is the user's
		parts << "fast";
	frame->setWindowTitle(parts.join(" - "));
}

// Screen changes can arrive during a fullscreen transition; refit after Qt settles.
void MainWin::updateScreen(QScreen* scr) {
	disconnect(screenGeometryConnection);
	disconnect(screenRateConnection);
	if (scr) {
		screenGeometryConnection = connect(scr, &QScreen::geometryChanged, this, [this]() {
			if (conf.vid.fullScreen) updateWindow();
		}, Qt::QueuedConnection);
		// a new mode on the same screen: the rate VSync locks to is asked again
		screenRateConnection = connect(scr, &QScreen::refreshRateChanged, this, &MainWin::vsyncProbe, Qt::QueuedConnection);
	}
	vsyncProbe();
	if (conf.vid.fullScreen) QTimer::singleShot(0, this, &MainWin::updateWindow);
}

// The display the window is on, asked again; the vblank tick runs while VSync is on.
void MainWin::vsyncProbe() {
	dsync_probe(frame->windowHandle());
	if (conf.vid.vsync) {
		if (!dsync_running() && dsync_start(pacing_vblank)) {
#if defined(USEOPENGL) && !BLOCKGL && !ISLEGACYGL
			// no vblank thread here: the view repaints on every swap, and each
			// swap that waited for the vblank is the tick
			if (glw && dsync_swaps_wait()) {
				connect(glw, &QOpenGLWidget::frameSwapped, this, [this]() {
					dsync_swapped();
					if (dsync_running()) glw->update();
				}, Qt::UniqueConnection);
				glw->update();
			}
#endif
		}
	} else if (dsync_running()) {
		dsync_stop();
	}
	vsyncUpdate();
}

// how far a machine's rate may be from the display's (or from a whole fraction
// of it) and still be run at it
#define VSYNC_TOLERANCE 0.045

// Lock the machine to the display or let it go. Asked on every fps tick: fast
// forward, slow motion and the rewind going back hand the time to the clock,
// and the lock comes back once they are over. A pause keeps it: nothing runs.
void MainWin::vsyncUpdate() {
	Computer* comp = conf.zx;
	int n = 0;
	double speed = 1.0;
	double rate = dsync_lock_rate();
	if (conf.vid.vsync && dsync_running() && !dsync_adaptive() && (rate > 0) && comp
			&& (comp->vid->nsPerFrame > 0) && !conf.emu.fast && (conf.emu.speed == 1.0)
			&& !rewind_active()) {
		double own = 1e9 / comp->vid->nsPerFrame;
		int k = (int)lround(rate / own);
		if (k >= 1) {
			double s = rate / (k * own);
			if (fabs(s - 1.0) <= VSYNC_TOLERANCE) {
				n = k;
				speed = s;
			}
		}
	}
	if (n && ((n != pacing_locked()) || (speed != pacing_lock_speed())))
		xlog(XLG_VIDEO, XLL_INFO, "vsync: locked, %i vblank(s) a frame, speed %.5f (display %.4f Hz)", n, speed, rate);
	else if (!n && pacing_locked())
		xlog(XLG_VIDEO, XLL_INFO, "vsync: unlocked");
	pacing_lock(n, speed);
	// said once for a rate, not on every way back from fast forward
	int shown = n ? (int)lround(rate * 100 / n) : 0;
	if (n && (shown != vsyncShown))
		setMessage(QString(" VSync: %0 Hz (%1%2 %) ").arg(rate / n, 0, 'f', 2)
			.arg((speed >= 1.0) ? "+" : "").arg((speed - 1.0) * 100, 0, 'f', 1), 2.0);
	if (n) vsyncShown = shown;
}

void MainWin::updateWindow() {
	block = 1;
	// the texture still holds the frame cut to the old bounds, and painting it
	// into the resized window would stretch it until the next frame arrives
	refit = 1;
	QSize wsz;
	Computer* comp = conf.zx;
	const QSize screenSize = SCREENSIZE;
	vid_upd_scale(screenSize);		// the picture and window use the same monitor
	// a size change can switch the shader off or bring it back (wantedShader)
	if (conf.vid.shd_support && (wantedShader() != shdLoaded))
		loadShader();
	// on the way out, asked before the bars come back: the resize they make takes the
	// window out of the state, and Qt puts it where it was when the state came - which,
	// for a start in fullscreen, is before it was ever shown, at 0,0
	bool back = !conf.vid.fullScreen && fsCovers();
	blockSignals(true);
	showBars();
	if (conf.vid.fullScreen) {
#if defined(__WIN32)
		fsTall = fsWantTall(fsHeld());
#endif
		wsz = screenSize + QSize(0, fsTall ? 1 : 0);
		// The state is asked for on the way in only. A window that covers the
		// screen has been out of the state since its first resize (the line it
		// grows for a menu, see fsCompose), and asking again puts it back to the
		// screen's exact size whatever size is set below - under the dialog that
		// is up, Options after Apply, which is then no longer drawn over it while
		// it still takes every key and click.
		if (!fsCovers()) {
			fsHome = QPoint(conf.xpos, conf.ypos);
#if defined(__WIN32)
			// Qt keeps the window's style here, to put it back once the state goes
			// (the first resize sees to that, after this returns). With a modal
			// dialog up - Options, on OK - that style has the window disabled for
			// the dialog, and put back after the dialog has gone it leaves the
			// window taking no input at all: so it is enabled for the moment the
			// style is kept.
			HWND hwnd = reinterpret_cast<HWND>(frame->winId());
			bool blocked = !IsWindowEnabled(hwnd);
			if (blocked) EnableWindow(hwnd, TRUE);
			frame->setWindowState(frame->windowState() | Qt::WindowFullScreen);
			if (blocked) EnableWindow(hwnd, FALSE);
#else
			frame->setWindowState(frame->windowState() | Qt::WindowFullScreen);
#endif
		}
	} else {
		// the picture: a whole number of pixels per dot, or it would be
		// resampled and some columns come out a pixel wider than others
		wsz = QSize(drawW, drawH);
		tbSize(toolBar, wsz.width());		// Auto: as the new width allows
		// Qt 5 forgets a widget is fullscreen once it has been resized - the layout
		// does that - while its window stays so, and leaving would then do nothing,
		// title bar never coming back: the widget is told fullscreen again first.
		QWindow* win = frame->windowHandle();
		if (win && (win->windowStates() & Qt::WindowFullScreen))
			frame->setWindowState(frame->windowState() | Qt::WindowFullScreen);
		frame->setWindowState(frame->windowState() & ~Qt::WindowFullScreen);
		// back on the screen with its title bar, once it has its size
		if (back) QTimer::singleShot(0, this, &MainWin::placeWindow);
	}
	setFixedSize(wsz);
	blockSignals(false);
	// the buffer holds the whole raster, whatever part of it is shown
	bytesPerLine = comp->vid->full.x * 8;
	bufSize = bytesPerLine * comp->vid->full.y * (comp->vid->linedbl ? 2 : 1);
	updateHead();
	block = 0;
	emit s_keywin_snap();		// a docked keyboard follows the new size
}

// false when one of them is to stay: cancelled, or its save failed
bool MainWin::saveChanged(bool tape) {
	for (int i = 0; i < 4; i++)
		if (saveChangedDisk(conf.zx, i) != ERR_OK) return false;
	return !tape || (saveChangedTape(conf.zx) == ERR_OK);
}

void MainWin::pause(bool p, int msk) {
	// fast mode leaves most frames undrawn: a pause of the user's own waits for
	// the machine to draw one whole (fast_picture_frame), the others stop it now
	if (p && (msk & PR_PAUSE) && conf.emu.fast && !conf.emu.pause && fast_picture_busy()) {
		conf.emu.pauseReq |= PR_PAUSE;
		msk &= ~PR_PAUSE;
	} else {
		conf.emu.fast = 0;
	}
	if (p) {
		conf.emu.pause |= msk;
	} else {
		conf.emu.pause &= ~msk;
		conf.emu.pauseReq &= ~msk;
	}
	int paused = conf.emu.pause || conf.emu.pauseReq;
	if (!grabMice || (paused && grabMice)) {
		releaseMouse();
	}
	if (!paused) {
		if (grabMice) {
			grabMouse(QCursor(Qt::BlankCursor));
			mouseRecenter();	// the pointer went its own way while paused
		}
		mapReplayHeld(conf.gpctrl->gpada);
		mapReplayHeld(conf.gpctrl->gpadb);
	}
}

