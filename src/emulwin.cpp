// off and on again: what a reset keeps (RAM, a divMMC's MAPRAM) goes too
void MainWin::hardReset() {
	emu_lock();
	xm_power_cycle();
	emu_unlock();
}

// A reset to one of the ROMs, from a hotkey: a machine that has no such start
// says so and stays as it is
void MainWin::resetTo(int res) {
	if (xm_reset_targets().contains(res)) {
		resetMachine(res);
		return;
	}
	const char* nam = (res == RES_48) ? "48K" : (res == RES_128) ? "128K" : (res == RES_DOS) ? "DOS" : "Service";
	setMessage(QString(" no reset to %0 here ").arg(nam));
}

// A reset from the running machine's window: one landing mid-opcode lets the opcode
// finish on the new state, and a jump then takes the pc back from the reset.
void MainWin::resetMachine(int res) {
	emu_lock();		// reset re-inits the hardware
	x_user_reset(conf.zx, res);
	emu_unlock();
}

// the board's own turbo, one of the steps it declares
void MainWin::setTurbo(int idx) {
	Computer* comp = conf.zx;
	if (comp->turboCount < 2) {
		setMessage(" model has no Turbo ");
	} else if (comp->rzx.play) {
		setMessage(" not in RZX ");
	} else {
		emu_lock();		// the new clock re-inits the hardware
		xm_turbo_step(comp, idx);
		emu_unlock();
		setMessage(QString(" %0 MHz (x%1) ").arg(xspeed_clock(), 0, 'g', 6)
			.arg(comp->turboStep));
	}
}


