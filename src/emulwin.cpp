// The picture covers the screen, so it sees every move that is not over the
// bar: one well below it, with no menu of it open, takes the bar away.
void MainWin::fsReveal(int y) {
	fsY = y;
	if (!fsBar || !conf.vid.fullScreen || grabMice) return;
	if (fsBar->isVisible()) {
		int bottom = fsBar->height() + (fsTool->isVisible() ? fsTool->height() : 0);
		if ((y > bottom + FS_EDGE) && !QApplication::activePopupWidget())
			fsHide();
	} else if ((y <= FS_EDGE) && !fsShow.isActive()) {
		fsShow.start(FS_DELAY);
	}
}

void MainWin::fsHide() {
	fsShow.stop();
	if (fsBar && fsBar->isVisible()) {
		tbLetGo();		// hidden, its button lets go of the mode
		fsBar->hide();
		fsTool->hide();
		setFocus();
	}
	fsCompose(false);
}

// A window that covers the monitor exactly is scanned out on its own, past the
// compositor, and a menu opened over it is never drawn. One line taller - off
// the bottom of the screen - it is composed with the rest. With Low latency it
// is made that only while a menu is up, and the switch flashes the screen;
// without, it stays composed, and the compositor's frame of lag is the price.
// on: a menu is about to open. Says whether it changed: the menu waits for the switch.
bool MainWin::fsCompose(bool on) {
#if defined(__WIN32)
	if (!conf.vid.fullScreen) {
		fsTall = 0;
		return false;
	}
	on = fsWantTall(on || fsHeld());
	// The window is asked, not the flag: the system can put a fullscreen
	// window back to the screen's size behind our back, and a menu opened
	// over it then is never drawn - while it holds the mouse and the keys.
	QSize scr = SCREENSIZE;
	bool tall = frame->height() > scr.height();
	if ((on == tall) && (on == bool(fsTall))) return false;
	fsTall = on;
	if (on && (size().height() > scr.height()))
		setFixedSize(scr);		// the same size again would change nothing
	setFixedSize(scr + QSize(0, on ? 1 : 0));
	xlog(XLG_GUI, XLL_INFO, "fullscreen: %s, window was %ix%i", on ? "composed" : "on its own again",
		frame->width(), frame->height());
	return on;
#else
	(void)on;
	return false;
#endif
}

// The window covers the screen - exactly, or the line taller - from its corner:
// fullscreen as it is once it has been resized there, whatever state Qt keeps.
bool MainWin::fsCovers() {
	if (frame->isFullScreen()) return true;
#if QT_VERSION >= QT_VERSION_CHECK(5,14,0)
	QRect scr = screen()->geometry();
#else
	QRect scr = QApplication::desktop()->screenGeometry();
#endif
	QRect fg = frame->geometry();
	return (fg.topLeft() == scr.topLeft()) && (fg.width() == scr.width()) && (fg.height() >= scr.height());
}

// a window of ours, not a menu or a tip: those are seen to by fsCompose's callers
static bool fs_window(QWidget* w) {
	Qt::WindowType type = w->windowType();
	return (type != Qt::Popup) && (type != Qt::ToolTip);
}

// What has to be seen over the picture: a menu, the bar at the top, or a window
// of ours - the docked keyboard, say, which is otherwise never drawn over one
// scanned out on its own, yet takes the clicks.
bool MainWin::fsHeld() {
	if (QApplication::activePopupWidget() || (fsBar && fsBar->isVisible())) return true;
	QRect scr = frame->geometry();
	foreach(QWidget* w, QApplication::topLevelWidgets()) {
		if ((w == frame) || !w->isVisible() || w->isMinimized() || !fs_window(w)) continue;
		if (w->frameGeometry().intersects(scr)) return true;
	}
	return false;
}

// a window has come, gone or moved
void MainWin::fsOverlay(QWidget* w) {
	if ((w != frame) && fs_window(w)) fsCompose(false);
}

// Back from fullscreen: where the window was, else in the middle - either way
// on a screen, title bar in view. Asked for once the window has its size back.
void MainWin::placeWindow() {
	// fsHome, not conf: the moves of the way out have been written there meanwhile.
	// -1,-1 is a window that has had no place yet: one started in fullscreen.
	QScreen* scr = (fsHome != QPoint(-1, -1)) ? QGuiApplication::screenAt(fsHome + QPoint(40, 10)) : nullptr;
	bool kept = (scr != nullptr);
	if (!scr) scr = frame->screen();
	QRect avail = scr->availableGeometry();
	QRect fg = frame->frameGeometry();
	QPoint at = kept ? fsHome : avail.center() - QPoint(fg.width() / 2, fg.height() / 2);
	at.setX(std::max(avail.left(), std::min(at.x(), avail.right() + 1 - fg.width())));
	at.setY(std::max(avail.top(), std::min(at.y(), avail.bottom() + 1 - fg.height())));
	frame->move(at);
}

